AMBER = (239, 185, 101)
BLACK = (0, 0, 0)


def rows(ch, table):
    return table.get(ch, table.get(ch.upper(), SMALL["?"])).split("/")


def width(text, table=SMALL):
    return max(0, sum(len(rows(c, table)[0]) + 1 for c in str(text)) - 1)


def text(im, xy, value, ink=WHITE, table=SMALL, limit=None):
    value = str(value)
    x, y = xy
    if limit is not None and width(value, table) > limit:
        raise ValueError(f"Text does not fit: {value!r}")
    d = ImageDraw.Draw(im)
    for ch in value:
        grid = rows(ch, table)
        if x < 0 or y < 0 or x + len(grid[0]) > im.width or y + len(grid) > im.height:
            raise ValueError(f"Text outside canvas: {value!r}")
        for j, row in enumerate(grid):
            for i, v in enumerate(row):
                if v == "1":
                    d.point((x + i, y + j), fill=ink)
        x += len(grid[0]) + 1
    return x


def hint(im, x, y, condition):
    d = ImageDraw.Draw(im)
    if condition in {"clear", "clear_night"}:
        d.rectangle((x + 1, y + 1, x + 3, y + 3), fill=AMBER)
        for xy in [(x + 2, y), (x, y + 2), (x + 4, y + 2), (x + 2, y + 4)]:
            d.point(xy, fill=AMBER)
    elif condition in {"snow", "heavy_snow"}:
        d.line((x, y + 2, x + 4, y + 2), fill=BLUE)
        d.line((x + 2, y, x + 2, y + 4), fill=BLUE)
    elif condition in {"storm", "storm_hail"}:
        d.line([(x + 3, y), (x + 1, y + 2), (x + 3, y + 2), (x + 1, y + 4)], fill=AMBER)
    elif condition == "unknown":
        text(im, (x, y), "?", SOFT)
    else:
        d.rectangle((x, y + 1, x + 4, y + 2), fill=SOFT)
        d.rectangle((x + 1, y, x + 3, y + 1), fill=SOFT)
        if condition in {"rain", "drizzle", "heavy_rain", "freezing_rain"}:
            d.point((x + 1, y + 4), fill=BLUE)
            d.point((x + 3, y + 4), fill=BLUE)


def n(value):
    return "--" if value is None else str(round(value))
